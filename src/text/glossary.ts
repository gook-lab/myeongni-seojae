/**
 * 명리서재 — 용어
 *
 * ─────────────────────────────────────────────────────────────────────────
 * 왜 필요한가
 *
 * 이 앱은 편관·정인·장생·공망·지장간 같은 말을 계속 쓴다. 사주를 아는
 * 사람에게는 당연한 말이지만, 관객은 부모님 세대다. 모르는 말이 나오면
 * 물어볼 데가 없어서 그냥 넘긴다. 그러면 화면에 적힌 것의 절반이 그림이 된다.
 *
 * 십성 설명(GLOSS)은 원래부터 만들어져 있었는데 **어느 화면에서도 쓰이지
 * 않고 있었다.** 계산해놓고 안 쓰던 것이 또 있었던 셈이다.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * 사전처럼 쓰지 않는다
 *
 * "비견(比肩): 어깨를 나란히 한다는 뜻으로…" 같은 한자 풀이로 시작하면
 * 읽다가 만다. 그게 **화면 어디에 나오는 말인지**부터 적는다.
 */
import { GLOSS } from './interpret';
import { STAGE_TEXT } from './stage-text';

export interface GlossEntry {
  term: string;
  /** 화면 어디에서 만나는 말인가 */
  where: string;
  body: string;
}

export interface GlossSection {
  title: string;
  lede: string;
  entries: GlossEntry[];
}

