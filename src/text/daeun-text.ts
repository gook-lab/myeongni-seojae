/** 현재 대운일 때 문단 앞에 붙는 한 줄. */
export const CURRENT_DAEUN_PREFIX = '지금 지나고 있는 10년입니다.';

/** 아직 오지 않은 대운. */
export const FUTURE_DAEUN_PREFIX = '앞으로 만나게 될 10년입니다.';

/** 이미 지나온 대운 — 대조해보라고 권한다. */
export const PAST_DAEUN_PREFIX = '이미 지나온 10년입니다. 그때가 어땠는지 맞춰보세요.';

export function daeunPrefix(startYear: number, endYear: number, currentYear: number): string {
  if (currentYear > endYear) return PAST_DAEUN_PREFIX;
  if (currentYear < startYear) return FUTURE_DAEUN_PREFIX;
  return CURRENT_DAEUN_PREFIX;
}
