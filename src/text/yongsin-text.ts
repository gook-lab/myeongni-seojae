export function strengthLead(score: number, support: number, drain: number, slots: number): string {
  return `${slots}개 자리를 무게로 재서 돕는 쪽 ${support}, 빼는 쪽 ${drain} 입니다. 돕는 비율 ${Math.round(score * 100)}%.`;
}
