export function balanceLead(total: number, strongest: Element, count: number): string {
  return `여덟 자 중 ${total}자를 셌습니다. ${strongest}${josa(strongest, '이', '가')} ${count}자로 가장 강합니다.`;
}

export function missingLead(missing: Element[]): string {
  const list = missing.join('·');
  return `${list}${josa(list, '이', '가')} 하나도 없습니다.`;
}

